function makeResult(
  id: string,
  examId: string,
  examName: string,
  student: Student,
  scores: Array<[string, string, number]>,
  status: 'Draft' | 'Verified' | 'Published'
): StudentResult {
  const computed = computeOverallResult(
    scores.map(([subjectCode, subjectName, obtainedMarks]) => ({
      subjectCode,
      subjectName,
      fullMarks: 100,
      passMarks: 33,
      obtainedMarks,
    }))
  );
  return {
    id,
    examId,
    examName,
    academicYear: '2026',
    studentId: student.studentId,
    studentName: student.name,
    studentNameBn: student.nameBn,
    className: student.className,
    section: student.section,
    roll: student.roll,
    marks: computed.marks,
    totalMarks: computed.totalMarks,
    gpa: computed.gpa,
    overallGrade: computed.overallGrade,
    passed: computed.passed,
    status,
    updatedBy: status === 'Published' ? 'পরীক্ষা নিয়ন্ত্রক' : 'তাহমিনা ইয়াসমিন',
    updatedAt: '2026-11-12',
  };
}

